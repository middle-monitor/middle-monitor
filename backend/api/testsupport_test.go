// sqlmockDB pairs a mock database with its expectation recorder, so a table
// driven test can build one per case without repeating the wiring.
type sqlmockDB struct {
	*sql.DB
	mock sqlmock.Sqlmock
}

// orgRequest builds an authenticated org-scoped request with the given mux vars.
func orgRequest(method, target, body string, vars map[string]string) *http.Request {
	var r *http.Request
	if body == "" {
		r = httptest.NewRequest(method, target, nil)
	} else {
		r = httptest.NewRequest(method, target, strings.NewReader(body))
	}
	r = orgContext(r, 1, 7)
	if vars != nil {
		r = mux.SetURLVars(r, vars)
	}
	return r
}

// A host scope that matches nothing must return nothing: silently widening to
// the whole org would show another host's metrics under a host filter.
func TestSeriesHostScopeNeverWidensToTheWholeOrg(t *testing.T) {
	db, mock, _ := sqlmock.New()
	defer db.Close()

	names, scoped, ok := seriesHostScope(db, httptest.NewRequest("GET", "/x", nil), 1)
	if scoped || !ok || names != nil {
		t.Fatalf("an unscoped request is not scoped: %v %v %v", names, scoped, ok)
	}

	mock.ExpectQuery("SELECT name FROM hosts WHERE id").WillReturnRows(sqlmock.NewRows([]string{"name"}))
	_, scoped, ok = seriesHostScope(db, httptest.NewRequest("GET", "/x?host_id=4", nil), 1)
	if !scoped || ok {
		t.Fatal("a host scope matching nothing must yield nothing")
	}

	mock.ExpectQuery("SELECT name FROM hosts WHERE host_group_id").
		WillReturnRows(sqlmock.NewRows([]string{"name"}).AddRow("web-01").AddRow("web-02"))
	names, scoped, ok = seriesHostScope(db, httptest.NewRequest("GET", "/x?host_group_id=2", nil), 1)
	if !scoped || !ok || len(names) != 2 {
		t.Fatalf("group scope resolved to %v", names)
	}

	mock.ExpectQuery("SELECT name FROM hosts").WillReturnError(errors.New("down"))
	_, scoped, ok = seriesHostScope(db, httptest.NewRequest("GET", "/x?host_id=4", nil), 1)
	if !scoped || ok {
		t.Fatal("a failed scope lookup must not widen the query either")
	}
}

// The unsubscribe link is generated by the outreach sender in another language.
// This value was produced by that sender: if this test fails, valid opt-outs are
// being rejected, which is the one failure mode with legal consequences.
func TestUnsubscribeTokenMatchesTheSender(t *testing.T) {
	got := unsubscribeToken("contact@acme.fr", "s3cr3t")
	if want := "d7290b723c1f31e5"; got != want {
		t.Fatalf("token %q, want %q", got, want)
	}
}
