// adminRequest builds an authenticated org-scoped request whose session carries
// the admin role, for the routes that gate on it.
func adminRequest(method, target, body string) *http.Request {
	r := httptest.NewRequest(method, target, strings.NewReader(body))
	claims := &services.JWTClaims{OrganizationID: 1, UserID: 7, Role: "admin", Email: "admin@example.com"}
	return r.WithContext(context.WithValue(r.Context(), middleware.ClaimsContextKey, claims))
}

// stubChatCompletion serves one canned OpenAI-compatible answer and returns its
// base URL.
func stubChatCompletion(t *testing.T, body string) string {
	t.Helper()
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		_, _ = w.Write([]byte(body))
	}))
	t.Cleanup(server.Close)
	return server.URL
}

// muxVars attaches path variables to a request, as the router would.
func muxVars(r *http.Request, vars map[string]string) *http.Request {
	return mux.SetURLVars(r, vars)
}

// seenArg is a sqlmock argument that matches anything and records that it was
// compared, so a test can assert a statement ran without having to predict how
// many other statements the code under test issues.
type seenArg struct{ hit *bool }

func (a seenArg) Match(driver.Value) bool {
	*a.hit = true
	return true
}

